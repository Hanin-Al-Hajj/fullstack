export const lang = () => (document.documentElement.lang || 'en').slice(0, 2);

// __('Add to cart') returns the Arabic text on Arabic pages.
// __('Only :n left', { n: 3 }) fills in the :n placeholder.
export const __ = (text, vars = {}) => {
    let out = lang() === 'ar' ? ar[text] ?? text : text;
    Object.entries(vars).forEach(([key, value]) => {
        out = out.replaceAll(`:${key}`, value);
    });
    return out;
};
